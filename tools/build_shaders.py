#!/usr/bin/env python3
"""Compile the SDK GLSL shaders to SPIR-V and embed them as C arrays.

Requires glslangValidator and spirv-val (Debian: glslang-tools, spirv-tools).
The generated C file is committed so a console-only build needs no shader
compiler.

Usage: python3 tools/build_shaders.py [--check]
"""
import argparse
import hashlib
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHADERS = {
    "ui_vert": ("sdk/shaders/ui.vert", "vert"),
    "ui_frag": ("sdk/shaders/ui.frag", "frag"),
    "tri_vert": ("sdk/shaders/tri.vert", "vert"),
    "tri_frag": ("sdk/shaders/tri.frag", "frag"),
}
TARGET = ["--target-env", "vulkan1.2"]


def compile_one(source: Path, stage: str, out: Path) -> None:
    compiler = shutil.which("glslangValidator")
    if compiler is None:
        raise SystemExit("glslangValidator not found (apt install glslang-tools)")
    subprocess.run([compiler, "-V", *TARGET, str(source), "-o", str(out)], check=True)
    validator = shutil.which("spirv-val")
    if validator:
        subprocess.run([validator, *TARGET, str(out)], check=True)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    blobs = {}
    with tempfile.TemporaryDirectory() as tmp:
        for name, (relative, stage) in SHADERS.items():
            target = Path(tmp) / f"{name}.spv"
            compile_one(ROOT / relative, stage, target)
            blobs[name] = target.read_bytes()

    lines = [
        "/* Generated by tools/build_shaders.py - do not edit.",
        " * Source: " + ", ".join(v[0] for v in SHADERS.values()),
        " */",
        "#include <stdint.h>",
        '#include "hbx_ui_shaders.h"',
        "",
    ]
    for name, data in blobs.items():
        digest = hashlib.sha256(data).hexdigest()
        lines.append(f"/* {name}: {len(data)} bytes, sha256 {digest} */")
        lines.append(f"const uint32_t hbx_shader_{name}[] = {{")
        words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
        for i in range(0, len(words), 8):
            lines.append("    " + ",".join(f"0x{word:08x}u" for word in words[i:i + 8]) + ",")
        lines.append("};")
        lines.append(f"const uint32_t hbx_shader_{name}_words = {len(words)}u;")
        lines.append("")

    text = "\n".join(lines)
    target_c = ROOT / "sdk/src/hbx_ui_shaders.c"
    header = ROOT / "sdk/include/hbx_ui_shaders.h"
    header_text = """/* Generated by tools/build_shaders.py - do not edit. */
#ifndef HBX_UI_SHADERS_H
#define HBX_UI_SHADERS_H

#include <stdint.h>

extern const uint32_t hbx_shader_ui_vert[];
extern const uint32_t hbx_shader_ui_vert_words;
extern const uint32_t hbx_shader_ui_frag[];
extern const uint32_t hbx_shader_ui_frag_words;
extern const uint32_t hbx_shader_tri_vert[];
extern const uint32_t hbx_shader_tri_vert_words;
extern const uint32_t hbx_shader_tri_frag[];
extern const uint32_t hbx_shader_tri_frag_words;

#endif
"""
    if args.check:
        if not target_c.exists() or target_c.read_text() != text:
            print("shader blobs are stale; run tools/build_shaders.py", file=sys.stderr)
            return 1
        print("shader blobs up to date")
        return 0

    target_c.write_text(text)
    header.write_text(header_text)
    for name, data in blobs.items():
        print(f"{name}: {len(data)} bytes sha256 {hashlib.sha256(data).hexdigest()[:16]}")
    print(f"wrote {target_c.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
