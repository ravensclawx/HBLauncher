#!/usr/bin/env python3
"""hbx-build - compile an HBLauncher Native SDK app package.

An app directory looks like:

    apps/<id>/
      manifest.json      package metadata (id, name, version, abi, kind, ...)
      src/*.c, *.S       freestanding sources (entry point: hbx_app_main)
      assets/...         files exposed through hbx_asset()
      icon.png           96x96 icon (optional; a letter tile is used otherwise)
      build/             generated: code.bin, data.bin, report.json

Fixed addresses by default: code at 0x09000000, data at 0x0B000000.  The
launcher owns 0x08000000/0x0A000000, so the two never collide.

Usage:
  hbx-build.py <app-dir> [--out DIR] [--code-base 0x09000000]
               [--data-base 0x0B000000] [--clean] [--check]

Exit codes: 0 ok, 1 build error, 2 usage error.
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
SDK = ROOT / "sdk"
CFLAGS = [
    "-std=gnu11", "-O2", "-ffreestanding", "-nostdlib", "-fno-builtin",
    "-fno-pic", "-fno-pie", "-mcmodel=large", "-mbranch-protection=bti",
    "-march=armv8-a", "-fno-stack-protector", "-fno-asynchronous-unwind-tables",
    "-fno-unwind-tables", "-fno-common", "-ffunction-sections", "-fdata-sections",
    "-Wall", "-Wextra", "-Werror",
]
SUFFIXES = {".c", ".S", ".s"}


def write_imports_header(manifest, out):
    """hbx_imports.h: module offsets of the manifest's SDK imports, in order,
    so an app can resolve them itself when the host passes no import table
    (see hbx_imports_resolve in hbx_app.h)."""
    imports = manifest.get("imports", [])
    if not isinstance(imports, list) or not all(isinstance(n, str) for n in imports):
        fail("imports must be a list of SDK symbol names")
    table = json.loads((SDK / "sdk-symbols.json").read_text())["functions"] if imports else {}
    lines = ["/* Generated by hbx-build from manifest imports. */",
             "#pragma once", "#include <stdint.h>",
             f"#define HBX_IMPORT_COUNT {len(imports)}u"]
    offsets = []
    for index, name in enumerate(imports):
        if name not in table:
            fail(f"unknown SDK import {name}")
        offsets.append(f"0x{table[name]:x}ull")
        ident = re.sub(r"[^A-Za-z0-9_]", "_", name)
        lines.append(f"#define HBX_IMPORT_{ident} {index}u")
    lines.append("static const uint64_t hbx_import_offsets[] = {" +
                 (", ".join(offsets) if offsets else "0") + "};")
    (out / "hbx_imports.h").write_text("\n".join(lines) + "\n")


def fail(message, code=1):
    print("hbx-build: " + message, file=sys.stderr)
    raise SystemExit(code)


def tool(name):
    for prefix in ("aarch64-linux-gnu-", ""):
        candidate = shutil.which(prefix + name)
        if candidate:
            return candidate
    fail(f"missing toolchain program: {name} (install gcc-aarch64-linux-gnu)")
    return None


def load_manifest(app: Path) -> dict:
    path = app / "manifest.json"
    if not path.exists():
        fail(f"{path} is missing")
    try:
        manifest = json.loads(path.read_text())
    except json.JSONDecodeError as error:
        fail(f"{path}: {error}")
    required = ["id", "name", "version", "abi", "kind"]
    for key in required:
        if key not in manifest:
            fail(f"{path}: missing required field '{key}'")
    if not re.fullmatch(r"[a-z0-9][a-z0-9._-]{0,63}", manifest["id"]):
        fail(f"{path}: id must be lowercase [a-z0-9._-]")
    if manifest["abi"] != 3:
        fail(f"{path}: abi {manifest['abi']} is not supported (this SDK emits 3)")
    defines = manifest.get("defines", [])
    if not isinstance(defines, list) or not all(
            isinstance(d, str) and re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*(=[A-Za-z0-9_.]*)?", d)
            for d in defines):
        fail(f"{path}: defines must be a list of NAME or NAME=VALUE strings")
    if manifest["kind"] not in ("native", "nes", "sm64"):
        fail(f"{path}: kind must be native, nes or sm64")
    return manifest


def sources_of(app: Path, manifest=None):
    if manifest and isinstance(manifest.get("sources"), list):
        files = []
        for relative in manifest["sources"]:
            path = (app / relative).resolve()
            if not path.exists():
                fail(f"manifest source missing: {relative}")
            files.append(path)
        return files
    files = []
    for base in (app / "src", app):
        if not base.is_dir():
            continue
        for entry in sorted(base.iterdir()):
            if entry.is_file() and entry.suffix in SUFFIXES and entry.parent == base:
                if entry.parent == app and entry.name.startswith("crt0"):
                    continue
                files.append(entry)
    if not files:
        fail("no .c/.S sources in src/")
    return files


def link_script(code_base: int, data_base: int) -> str:
    return f"""/* generated by hbx-build */
ENTRY(_start)
SECTIONS
{{
  . = 0x{code_base:x};
  .text : {{
    *(.text.entry)
    *(.text .text.*)
  }}
  . = ALIGN(16);
  .rodata : {{ *(.rodata .rodata.*) }}
  . = ALIGN(16);
  __code_end = .;

  . = 0x{data_base:x};
  .data : {{ *(.data .data.*) }}
  . = ALIGN(16);
  __bss_start = .;
  .bss (NOLOAD) : {{
    *(.bss .bss.*)
    *(COMMON)
  }}
  . = ALIGN(16);
  __bss_end = .;
  __data_end = .;
}}
"""


def symbols_of(elf: Path) -> dict:
    output = subprocess.run([tool("nm"), str(elf)], capture_output=True, text=True).stdout
    result = {}
    for line in output.splitlines():
        parts = line.split()
        if len(parts) == 3:
            try:
                result[parts[2]] = int(parts[0], 16)
            except ValueError:
                pass
    return result


def main() -> int:
    parser = argparse.ArgumentParser(add_help=True)
    parser.add_argument("app")
    parser.add_argument("--out", default=None)
    parser.add_argument("--code-base", default="0x0c000000")
    parser.add_argument("--data-base", default="0x0d000000")
    parser.add_argument("--clean", action="store_true")
    args = parser.parse_args()

    app = Path(args.app).resolve()
    if not app.is_dir():
        fail(f"{app} is not a directory", 2)
    code_base = int(args.code_base, 0)
    data_base = int(args.data_base, 0)
    for name, value in (("code", code_base), ("data", data_base)):
        if value % 0x1000:
            fail(f"{name} base must be page aligned", 2)
    if code_base == (0x08000000) or data_base == (0x0A000000):
        fail("app bases may not overlap the launcher (0x08000000 / 0x0A000000)", 2)

    manifest = load_manifest(app)
    out = Path(args.out) if args.out else app / "build"
    if args.clean and out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True, exist_ok=True)

    write_imports_header(manifest, out)

    cc = tool("gcc")
    sources = sources_of(app, manifest)
    objects = []
    print(f"[hbx-build] {manifest['id']}: compiling {len(sources)} source(s)")
    for source in sources:
        obj = out / (source.name.replace(".", "_") + ".o")
        includes = [f"-I{SDK / 'include'}", f"-I{app / 'src'}", f"-I{app}", f"-I{out}"]
        src_dir = app / "src"
        if src_dir.is_dir():
            for directory in sorted(p for p in src_dir.rglob("*") if p.is_dir()):
                includes.append(f"-I{directory}")
        flags = list(CFLAGS) + [f"-D{d}" for d in manifest.get("defines", [])]
        # Vendored emulator sources are not ours to silence; build them with
        # warnings visible but not fatal.
        if "/core/" in source.as_posix() or "/compat/" in source.as_posix():
            flags = [flag for flag in flags if flag != "-Werror"]
        command = [cc, *flags, *includes, "-c", str(source), "-o", str(obj)]
        result = subprocess.run(command, capture_output=True, text=True)
        if result.returncode:
            sys.stderr.write(result.stderr)
            fail(f"compiling {source} failed")
        objects.append(obj)

    crt = out / "crt0.o"
    result = subprocess.run([cc, *CFLAGS, "-c", str(SDK / "src" / "crt0.S"), "-o", str(crt)],
                            capture_output=True, text=True)
    if result.returncode:
        sys.stderr.write(result.stderr)
        fail("compiling crt0.S failed")

    runtime_objects = []
    for runtime_source in ("hbx_app.c", "hbx_math.c", "hbx_ui_shaders.c"):
        runtime_object = out / (Path(runtime_source).stem + ".o")
        result = subprocess.run([cc, *CFLAGS, f"-I{SDK / 'include'}", "-c",
                                 str(SDK / "src" / runtime_source), "-o", str(runtime_object)],
                                capture_output=True, text=True)
        if result.returncode:
            sys.stderr.write(result.stderr)
            fail(f"compiling the SDK runtime ({runtime_source}) failed")
        runtime_objects.append(runtime_object)

    script = out / "link.ld"
    script.write_text(link_script(code_base, data_base))
    elf = out / "app.elf"
    link = subprocess.run([cc, *CFLAGS, "-no-pie", "-nostdlib", "-Wl,-T," + str(script),
                           "-Wl,--gc-sections", "-Wl,--build-id=none", "-o", str(elf),
                           str(crt), *[str(o) for o in runtime_objects], *[str(o) for o in objects], "-lgcc"],
                          capture_output=True, text=True)
    if link.returncode:
        sys.stderr.write(link.stderr)
        fail("link failed")

    code_bin = out / "code.bin"
    data_bin = out / "data.bin"
    subprocess.run([tool("objcopy"), "-O", "binary", "-j", ".text", "-j", ".rodata",
                    str(elf), str(code_bin)], check=True)
    subprocess.run([tool("objcopy"), "-O", "binary", "-j", ".data", str(elf), str(data_bin)],
                   check=True)

    symbols = symbols_of(elf)
    code = code_bin.read_bytes()
    data = data_bin.read_bytes()
    bss_start = symbols.get("__bss_start", data_base + len(data))
    bss_end = symbols.get("__bss_end", bss_start)
    if symbols.get("_start") != code_base:
        fail(f"entry is 0x{symbols.get('_start', 0):x}, expected 0x{code_base:x}")
    if symbols.get("hbx_app_main") is None:
        fail("app does not define hbx_app_main")

    report = {
        "format": "hblauncher-native-app/1",
        "id": manifest["id"],
        "kind": manifest["kind"],
        "abi": manifest["abi"],
        "codeBase": hex(code_base),
        "dataBase": hex(data_base),
        "entry": hex(symbols["_start"]),
        "spawn": hex(symbols["_spawn"]) if "_spawn" in symbols else None,
        "hbxAppMain": hex(symbols["hbx_app_main"]),
        "codeBytes": len(code),
        "codePages": (len(code) + 0xFFF) // 0x1000,
        "dataBytes": len(data),
        "bssBytes": max(0, bss_end - bss_start),
        "dataRegionBytes": max(0, bss_end - data_base),
        "codeSha256": hashlib.sha256(code).hexdigest(),
        "dataSha256": hashlib.sha256(data).hexdigest(),
    }
    (out / "report.json").write_text(json.dumps(report, indent=2) + "\n")
    print(f"[hbx-build] code {len(code)} B / {report['codePages']} pages, "
          f"data {len(data)} B, bss {report['bssBytes']} B")
    print(f"[hbx-build] code sha256 {report['codeSha256'][:16]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
