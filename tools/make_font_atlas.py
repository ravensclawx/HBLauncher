#!/usr/bin/env python3
"""Bake the HBLauncher Native type atlas into C.

Renders the printable ASCII range at the six SDK font faces into one 1024x1024
8-bit alpha atlas, then emits:

  sdk/src/hbx_font_data.c   atlas pixels + glyph metrics (freestanding, const)
  sdk/include/hbx_font.h    face/glyph structures and per-face counts
  assets/font_atlas.png     human-readable preview (not loaded at runtime)

The atlas is deterministic: same font file + same PIL/size => same bytes.
DejaVu Sans is distributed under the Bitstream Vera license (see
THIRD_PARTY.md); only the rendered bitmap is committed, not the font file.

Usage: python3 tools/make_font_atlas.py [--font-dir DIR] [--check]
"""
import argparse
import hashlib
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
ATLAS_SIZE = 1024
FIRST, LAST = 32, 126

FACES = [
    # name,        file,                pixel size, bold
    ("TITLE", "DejaVuSans-Bold.ttf", 88, True),
    ("H1", "DejaVuSans-Bold.ttf", 34, True),
    ("H2", "DejaVuSans-Bold.ttf", 26, True),
    ("BODY", "DejaVuSans.ttf", 20, False),
    ("SMALL", "DejaVuSans.ttf", 17, False),
    ("TINY", "DejaVuSans.ttf", 14, False),
]
TITLE_CHARS = set(" ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789.-+&")


def find_font(directory: Path, name: str) -> Path:
    candidate = directory / name
    if candidate.exists():
        return candidate
    for base in (
        Path("/usr/share/fonts/truetype/dejavu"),
        Path("/usr/share/fonts/TTF"),
        Path("/usr/share/fonts"),
    ):
        for found in base.rglob(name):
            return found
    raise SystemExit(f"font not found: {name} (pass --font-dir)")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--font-dir", type=Path, default=Path("/usr/share/fonts/truetype/dejavu"))
    parser.add_argument("--check", action="store_true", help="verify committed output is current")
    args = parser.parse_args()

    atlas = Image.new("L", (ATLAS_SIZE, ATLAS_SIZE), 0)
    draw = ImageDraw.Draw(atlas)

    faces = []
    pen_x, pen_y, row_height = 2, 2, 0
    for name, filename, size, bold in FACES:
        font = ImageFont.truetype(str(find_font(args.font_dir, filename)), size)
        ascent, descent = font.getmetrics()
        chars = [(c, chr(c)) for c in range(FIRST, LAST + 1)]
        if name == "TITLE":
            chars = [(c, chr(c)) for c in range(FIRST, LAST + 1) if chr(c) in TITLE_CHARS]
        glyphs = {}
        for code, text in chars:
            left, top, right, bottom = draw.textbbox((0, 0), text, font=font)
            width, height = right - left, bottom - top
            advance = int(round(font.getlength(text)))
            if width <= 0 or height <= 0:
                glyphs[code] = (0, 0, 0, 0, 0, 0, advance)
                continue
            if pen_x + width + 2 > ATLAS_SIZE:
                pen_x = 2
                pen_y += row_height + 3
                row_height = 0
            if pen_y + height + 2 > ATLAS_SIZE:
                raise SystemExit(f"atlas overflow at face {name} U+{code:04X}")
            draw.text((pen_x - left, pen_y - top), text, font=font, fill=255)
            glyphs[code] = (pen_x, pen_y, width, height, left, top, advance)
            pen_x += width + 3
            row_height = max(row_height, height)
        pen_x = 2
        pen_y += row_height + 6
        row_height = 0
        faces.append({
            "name": name, "size": size, "bold": bold,
            "ascent": ascent, "descent": descent, "glyphs": glyphs,
        })

    pixels = atlas.tobytes()
    digest = hashlib.sha256(pixels).hexdigest()

    header = Path(ROOT / "sdk/include/hbx_font.h")
    header.write_text(f"""/* Generated by tools/make_font_atlas.py - do not edit.
 * Atlas: {ATLAS_SIZE}x{ATLAS_SIZE} R8, sha256 {digest}
 * Faces: {', '.join(f['name'] + ' ' + str(f['size']) for f in faces)}
 * License: rendered DejaVu Sans bitmaps (Bitstream Vera license).
 */
#ifndef HBX_FONT_H
#define HBX_FONT_H

#include <stdint.h>

#define HBX_ATLAS_SIZE {ATLAS_SIZE}u
#define HBX_GLYPH_FIRST {FIRST}u
#define HBX_GLYPH_LAST {LAST}u
#define HBX_GLYPH_COUNT (HBX_GLYPH_LAST - HBX_GLYPH_FIRST + 1u)
#define HBX_FACE_COUNT {len(faces)}u

struct hbx_glyph {{
    uint16_t x, y, w, h;   /* atlas pixel rect */
    int16_t ox, oy;        /* ink offset from the pen origin (top-left) */
    int32_t advance;       /* pen advance in pixels */
}};

struct hbx_face {{
    uint16_t size;
    uint16_t ascent, descent;
    const struct hbx_glyph *glyphs;  /* HBX_GLYPH_COUNT entries, indexed by code - 32 */
}};

extern const struct hbx_glyph hbx_font_glyphs[HBX_FACE_COUNT][HBX_GLYPH_COUNT];
extern const struct hbx_face hbx_faces[HBX_FACE_COUNT];

#endif
""")

    out = Path(ROOT / "launcher/src/font_metrics.c")
    lines = [
        "/* Generated by tools/make_font_atlas.py - do not edit.",
        f" * Atlas pixels: assets/font_atlas.r8 ({ATLAS_SIZE}x{ATLAS_SIZE} R8), sha256 {digest}.",
        " * The launcher receives those pixels from the host at runtime, so only the",
        " * metrics live in the image.",
        " */",
        '#include "hbx_font.h"',
        "",
    ]
    lines.append(f"const struct hbx_glyph hbx_font_glyphs[{len(faces)}][HBX_GLYPH_COUNT] = {{")
    for face in faces:
        lines.append(f"    /* {face['name']} {face['size']}px */ {{")
        row = []
        for code in range(FIRST, LAST + 1):
            g = face["glyphs"].get(code)
            if g is None:
                row.append("{0,0,0,0,0,0,0}")
            else:
                row.append("{" + ",".join(str(v) for v in g) + "}")
        for i in range(0, len(row), 6):
            lines.append("        " + ",".join(row[i:i + 6]) + ",")
        lines.append("    },")
    lines.append("};")
    lines.append("")
    lines.append("const struct hbx_face hbx_faces[HBX_FACE_COUNT] = {")
    for index, face in enumerate(faces):
        lines.append(f"    {{{face['size']}, {face['ascent']}, {face['descent']}, hbx_font_glyphs[{index}]}},")
    lines.append("};")
    lines.append("")
    text = "\n".join(lines)

    if args.check:
        current = out.read_text() if out.exists() else ""
        if current != text:
            print("font atlas C data is stale; run tools/make_font_atlas.py", file=sys.stderr)
            return 1
        print(f"font atlas up to date (sha256 {digest})")
        return 0

    out.write_text(text)
    preview = Path(ROOT / "assets/font_atlas.png")
    preview.parent.mkdir(parents=True, exist_ok=True)
    atlas.save(preview)
    (Path(ROOT / "assets/font_atlas.r8")).write_bytes(pixels)
    print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size} bytes)")
    print(f"wrote {header.relative_to(ROOT)}")
    print("wrote assets/font_atlas.r8 and assets/font_atlas.png")
    print(f"atlas sha256 {digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
